import {test,expect} from '@playwright/test';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
import {mkdtemp,copyFile,writeFile,mkdir,readdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
const release=resolve('../release/genshin抽卡模拟器.html');
test('离线交互、取消重启、手机布局与独立复制',async({page})=>{
 const errors:string[]=[],network:string[]=[];
 page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(/^https?:/.test(r.url()))network.push(r.url());});
 await page.route(/^https?:/,r=>r.abort());await page.goto(pathToFileURL(release).href);
 await page.getByText('抽卡体验',{exact:true}).click();
 await page.getByRole('spinbutton',{name:'这次先抽几抽'}).fill('25');
 await page.getByRole('button',{name:'开始抽'}).click();await expect(page.getByTestId('manual-result')).toBeVisible();
 await expect(page.getByRole('button',{name:'开始抽'})).toBeEnabled();
 await page.getByRole('button',{name:'开始抽'}).click();await expect(page.getByRole('button',{name:'开始抽'})).toBeEnabled();
 await page.getByText('跑一百万次看看',{exact:true}).click();await page.getByRole('button',{name:'开始跑 100 万次'}).click();
 await expect(page.getByTestId('batch-result')).toBeVisible();const start=Date.now();await page.getByRole('button',{name:'停下'}).click();
 await expect(page.getByRole('button',{name:'开始跑 100 万次'})).toBeEnabled();const cancelMs=Date.now()-start;expect(cancelMs).toBeLessThan(1000);
 await page.getByRole('spinbutton',{name:'准备了多少抽'}).fill('0');await page.getByRole('spinbutton',{name:'准备了多少抽'}).blur();
 await expect(page.getByText('设置改过了，下面的结果还是旧的',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'开始跑 100 万次'}).click();await expect(page.getByTestId('batch-result')).toHaveAttribute('data-completed','1000000');
 await expect(page.getByRole('button',{name:'开始跑 100 万次'})).toBeEnabled();await expect(page.getByText('还没有一次全部拿到',{exact:true})).toBeVisible();
 await page.getByText('抽卡体验',{exact:true}).click();
 await page.getByRole('button',{name:'开始抽'}).click();
 await expect(page.getByText('账号设置改过了，请先点「清空体验进度」，不然新设置会和旧进度混在一起。',{exact:true})).toBeVisible();
 await page.getByText('跑一百万次看看',{exact:true}).click();
 await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 await page.screenshot({path:'../doc/evidence/mobile-smoke.png',fullPage:true});
 expect(errors).toEqual([]);expect(network).toEqual([]);
 const dir=await mkdtemp(resolve(tmpdir(),'gacha-offline-'));await copyFile(release,resolve(dir,'祈愿.html'));
 await page.goto(pathToFileURL(resolve(dir,'祈愿.html')).href);await page.getByText('抽卡体验',{exact:true}).click();await page.getByRole('button',{name:'开始抽'}).click();await expect(page.getByTestId('manual-result')).toBeVisible();
 await writeFile('../doc/evidence/smoke.json',JSON.stringify({cancelMs,errors,network,independentCopy:dir,releaseFiles:await readdir('../release')},null,2));
});
test('百万真实参考性能',async({page,browser})=>{
 await page.route(/^https?:/,r=>r.abort());await page.goto(pathToFileURL(release).href);
 await page.getByRole('button',{name:'开始跑 100 万次'}).click();await expect(page.getByTestId('batch-result')).toHaveAttribute('data-completed','1000000',{timeout:180000});
 await expect(page.getByRole('button',{name:'开始跑 100 万次'})).toBeEnabled();
 const text=await page.getByTestId('batch-result').innerText();await mkdir('../doc/evidence',{recursive:true});
 await writeFile('../doc/evidence/benchmark.txt','Chrome '+browser.version()+'\n'+text);
 await page.screenshot({path:'../doc/evidence/desktop.png',fullPage:true});
});
